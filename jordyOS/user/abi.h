#ifndef JORDY_USER_ABI_H
#define JORDY_USER_ABI_H
#include <stdint.h>
#define USER_BASE 0x40000000ul
#define USER_IMAGE_LIMIT (8 * 1024 * 1024ul)
#define USER_STARTUP (USER_BASE + USER_IMAGE_LIMIT)
#define USER_STACK_BOTTOM (USER_STARTUP + 8192)
#define USER_STACK_SIZE (256 * 1024ul)
#define USER_STACK_TOP (USER_STACK_BOTTOM + USER_STACK_SIZE)
enum {
    USYS_EXIT, USYS_WRITE, USYS_READLINE, USYS_GETC, USYS_POLLC, USYS_YIELD,
    USYS_CLEAR, USYS_FILES, USYS_READ_FILE, USYS_WRITE_FILE, USYS_DELETE_FILE,
    USYS_PAINT, USYS_DRAWTEXT, USYS_TERMINAL, USYS_WAIT, USYS_IDENTITY
};
enum {
    UMODE_APP, UMODE_HEALTH, UMODE_KERNEL_READ, UMODE_KERNEL_WRITE,
    UMODE_PEER_READ, UMODE_PEER_WRITE, UMODE_HLT, UMODE_IO, UMODE_CR3,
    UMODE_CODE_WRITE, UMODE_DATA_EXEC, UMODE_NULL, UMODE_GUARD,
    UMODE_BAD_POINTER, UMODE_MARKER_WRITE, UMODE_MARKER_READ,
    UMODE_STARTUP_WRITE, UMODE_DIRECTION_FLAG, UMODE_FPU_CONTROL,
    UMODE_DIVIDE, UMODE_BAD_OPCODE
};
typedef struct { uint64_t mode, peer_address, marker_address; char command[96]; } UserStartup;
#endif
